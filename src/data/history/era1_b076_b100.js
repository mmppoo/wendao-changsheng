/** 终局计数的简写：T('coop') → { counter: { e1d_coop: 1 } } */
function T(tag, n = 1, more = {}) {
  return { ...more, counter: { [`e1d_${tag}`]: n, ...(more.counter || {}) } };
}

/** 选项：label、hint、结果文字、效果；extra 可带 require / requireHint / hideIf / cost / combat。 */
function C(label, hint, text, effects = {}, extra = {}) {
  return { label, hint, ...extra, outcome: { text, effects } };
}

/**
 * 历史事件节点。key 形如 'B076.zhongzhou.yuyuan'；第二段为五域或 tianxia（天下，domain 为 null）。
 * opt.major 缺省：五域为 true、天下为 false。
 */
function H(key, title, regions, window, baseline, text, choices, opt = {}) {
  const [chap, dom, slug] = key.split('.');
  const domain = DOMAIN_OF[dom] ?? null;
  const history = {
    key, domain, regions, window, baseline,
    major: opt.major ?? (domain !== null),
  };
  if (opt.minRealm) history.minRealm = opt.minRealm;
  return {
    id: `e1d_${chap.toLowerCase()}_${dom}_${slug}`,
    title, text, pool: 'history', weight: 0, choices, history,
  };
}

