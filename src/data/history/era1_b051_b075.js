const DOMAINS = new Set(['zhongzhou', 'beijing', 'dongling', 'xichui', 'nanze']);
/** 地区所属五域（与 engine/history.js 的 REGION_DOMAIN 一致）；山川小事按所在地区归域，只在本域传风闻。 */
const REGION_DOMAIN = {
  qingniu: 'nanze', luoxia: 'nanze', yaosen: 'dongling', guixu: 'dongling',
  beihuang: 'beijing', zhongzhou: 'zhongzhou', kunlun: 'xichui', jiuxiao: 'xichui',
};

/** 组装一件历史事件。dom 为五域之一，或 tianxia（天下大势，domain 记为 null）/ shanchuan（山川，domain 取所在地区之域）。 */
function ev(ch, dom, slug, regions, win, major, title, baseline, text, choices) {
  const base = (Number(ch.slice(1)) - 1) * 100;
  return {
    id: `h1c_${ch.toLowerCase()}_${dom}_${slug}`,
    title,
    text,
    pool: 'history',
    weight: 0,
    choices,
    history: {
      key: `${ch}.${dom}.${slug}`,
      domain: DOMAINS.has(dom) ? dom : (dom === 'shanchuan' && regions.length ? REGION_DOMAIN[regions[0]] : null),
      regions,
      window: [base + win[0], base + win[1]],
      baseline,
      major,
    },
  };
}

/** 普通选项。花钱的选项（stones 为负）改走 cost：钱不够时选项锁住，够了才扣。 */
const C = (label, hint, text, effects = {}) => {
  const { stones, ...rest } = effects;
  if (stones < 0) return { label, hint, cost: { stones: -stones }, outcome: { text, effects: rest } };
  return { label, hint, outcome: { text, effects } };
};
/** 带条件的选项。 */
const R = (require, requireHint, choice) => ({ ...choice, require, requireHint });
/** 斗法选项：叙事与效果写在胜负两端。 */
const FIGHT = (label, hint, enemy, win, lose) => ({ label, hint, combat: { enemy, win, lose } });

