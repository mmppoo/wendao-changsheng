/** 普通选项：label、hint、结果文字、效果；extra 可带 require / requireHint / hideIf / cost。 */
const C = (label, hint, text, effects = {}, extra = {}) => ({ label, hint, ...extra, outcome: { text, effects } });

/** 检定选项。 */
const Roll = (label, hint, p, attrs, success, fail, extra = {}) => ({
  label, hint, ...extra,
  roll: { p, attrs, success: { text: success[0], effects: success[1] || {} }, fail: { text: fail[0], effects: fail[1] || {} } },
});

/** 斗法选项。 */
const Fight = (label, hint, enemy, win, lose, extra = {}) => ({
  label, hint, ...extra,
  combat: { enemy, win: { text: win[0], effects: win[1] || {} }, lose: { text: lose[0], effects: lose[1] || {} } },
});

/** 历史事件节点。major 局势默认覆盖该域全部地区。 */
function H(ch, domain, slug, o) {
  const node = {
    id: `era1a_${ch.toLowerCase()}_${domain}_${slug}`,
    title: o.title,
    text: o.text,
    pool: 'history',
    weight: 0,
    choices: o.choices,
    history: {
      key: `${ch}.${domain}.${slug}`,
      domain,
      regions: o.regions || R[domain],
      window: o.window,
      baseline: o.baseline,
      major: o.major !== false,
    },
  };
  if (o.minRealm != null) node.history.minRealm = o.minRealm;
  return node;
}

