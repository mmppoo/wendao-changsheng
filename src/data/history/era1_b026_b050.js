/**
 * 生成一个历史事件节点。
 * ch：'B027'；domain：五域编号或 null（天下大势）；slug：短名；
 * o.at：本章内的年份偏移 [起, 止]（1—100），换算成第一纪元绝对年份。
 */
function H(ch, domain, slug, o) {
  const n = Number(ch.slice(1));
  const base = (n - 1) * 100;
  const h = {
    key: `${ch}.${domain || 'tianxia'}.${slug}`,
    domain: domain || null,
    regions: o.regions || (domain ? RG[domain] : []),
    window: [base + o.at[0], base + o.at[1]],
    baseline: o.baseline,
    major: o.major ?? true,
  };
  if (o.minRealm) h.minRealm = o.minRealm;
  return {
    id: `e1b_${ch.toLowerCase()}_${domain ? DS[domain] : 'tx'}_${slug}`,
    title: o.title,
    text: o.text,
    pool: 'history',
    weight: 0,
    choices: o.choices,
    history: h,
  };
}

/** 普通选项：label、hint、结果文字、效果，more 里放 require / requireHint / hideIf / cost。 */
function C(label, hint, text, effects = {}, more = {}) {
  return { label, hint, ...more, outcome: { text, effects } };
}

