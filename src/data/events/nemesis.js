/* 敌手生成：按 REALMS[r].powerMult 标定                                */
/* ------------------------------------------------------------------ */
const EXP_BASE = [110, 560, 2600, 11000, 50000, 240000, 1150000, 5400000];
const STONE_BASE = [70, 260, 900, 2400, 5500, 12000, 25000, 45000];

/** 系数：[hp, atk, def] × powerMult */
const K_LACKEY = [130, 13, 4]; // 第一段的随从，炼气可胜
// 越阶之敌：境界高一阶（借来或强催的修为，根基虚浮），系数故意低于高一阶的同阶标定，
// 但数值仍明显高于玩家所在境界的任何同阶敌手。实测：刚破境（0 层）的裸装角色胜率约 2–3 成，
// 同境第 3 层约 9 成以上。败了剧情照样推进，不会卡死。
const K_UP = [92, 9.2, 3.1];
const K_EVEN = [200, 18, 7.5]; // 第三段同阶
const K_FINAL = [210, 19, 8]; // 终局同阶巅峰

function foe(id, name, realm, k, trait, desc, rival = true) {
  const pm = REALMS[realm].powerMult;
  const def = {
    id, name, realm,
    hp: Math.round(k[0] * pm),
    atk: Math.round(k[1] * pm),
    def: Math.round(k[2] * pm),
    exp: Math.round(EXP_BASE[realm] * 1.25),
    stones: Math.round(STONE_BASE[realm] * 1.2),
    trait, desc,
  };
  if (rival) def.isRival = true;
  return def;
}

/** 宿敌战斗规格：固定敌手境界 */
const fight = (enemy, win, lose) => ({ enemy, preserveEnemyRealm: true, win, lose });

/** 触发条件 */
const arch = (id) => `flags.宿敌 == "${id}"`;
const stageWhen = (id, n, realmCond) => (n === 1
  ? `${arch(id)} && ${realmCond} && !flag("宿敌_1")`
  : `${arch(id)} && ${realmCond} && flag("宿敌_${n - 1}") && !flag("宿敌_${n}")`);
const retryWhen = (id) => `${arch(id)} && flag("宿敌_5") && flag("宿敌_待战") && !flag("宿敌_了") && hp >= char.maxHp * 0.7`;
/** 主动暂避后：每暂避一次，须再高一个大境界才会重新插入，绝不连环纠缠 */
const rearmWhen = (id) => `${arch(id)} && flag("宿敌_5") && flag("宿敌_缓战") && !flag("宿敌_待战") && !flag("宿敌_了") && realm >= 6 + count("宿敌_缓") && hp >= char.maxHp * 0.7`;

const S1 = '(realm >= 1 || layer >= 3)';
const S2 = 'realm >= 1';
const S3 = 'realm >= 2';
const S4 = 'realm >= 4';
const S5 = 'realm >= 6';

function triggersFor(id) {
  return [
    { id: `nem_${id}_1`, when: stageWhen(id, 1, S1) },
    { id: `nem_${id}_2`, when: stageWhen(id, 2, S2) },
    { id: `nem_${id}_3`, when: stageWhen(id, 3, S3) },
    { id: `nem_${id}_4`, when: stageWhen(id, 4, S4) },
    { id: `nem_${id}_5`, when: stageWhen(id, 5, S5) },
    { id: `nem_${id}_5b`, when: retryWhen(id) },
    { id: `nem_${id}_5b`, when: rearmWhen(id) },
  ];
}

