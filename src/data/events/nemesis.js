/**
 * 宿敌系统：每一世由引擎随机指定一种宿敌原型，五段剧情贯穿一生。
 *
 * 引擎约定：
 * - 开局时 flags.宿敌 = 原型 id（字符串），flags.宿敌名 = 生成的姓名。
 * - 正文用 {rival} 指代宿敌姓名（引擎替换）；另可用 {name} {realm} {sect}。
 * - 宿敌战的敌手定义带 isRival: true，引擎显示宿敌姓名、不做境界缩放；
 *   此处同时传 preserveEnemyRealm: true，保证现有引擎下境界也固定。
 *
 * 世界观：只用宁朝五域审定稿与专名表里的地名、势力；结丹以上不写境界名（审定稿只到元婴，
 * 引擎境界与之不一一对应），统一写「高出一整个大境界」「与你同境」。
 *
 * 条件写法注意：flag() 会把值转成布尔，所以判断原型必须写 flags.宿敌 == "xxx"，
 * 不能写 flag("宿敌") == "xxx"。
 *
 * 进度旗标：
 * - 宿敌_1 … 宿敌_5：各段首节点 onEnter 写入（逃跑也不会卡住进度）。
 * - 宿敌_越阶 / 宿敌_越阶二：第二、四段越阶获胜。宿敌_清算：第三段公开清算获胜。
 * - 宿敌_斩 / 宿敌_废 / 宿敌_恕：终局处置；宿敌_了：宿敌线了结（结局判定用）。
 * - 宿敌_待战：终局一战未分胜负（败或遁），伤愈后由重战触发器再次插入。
 * - 宿敌_缓战 / counter 宿敌_缓：终局选择暂避；每暂避一次，须再高一个大境界才会重新插入。
 */
import { REALMS } from '../realms.js';

